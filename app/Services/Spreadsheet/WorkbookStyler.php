<?php

namespace App\Services\Spreadsheet;

use DateTimeInterface;
use PhpOffice\PhpSpreadsheet\Cell\DataType;
use PhpOffice\PhpSpreadsheet\Shared\Date;
use PhpOffice\PhpSpreadsheet\Spreadsheet;
use PhpOffice\PhpSpreadsheet\Style\Alignment;
use PhpOffice\PhpSpreadsheet\Style\Border;
use PhpOffice\PhpSpreadsheet\Style\Fill;
use PhpOffice\PhpSpreadsheet\Worksheet\PageSetup;
use PhpOffice\PhpSpreadsheet\Worksheet\Worksheet;

class WorkbookStyler
{
    public const string Ink = '172033';

    public const string Muted = '667085';

    public const string Border = 'CBD5E1';

    public const string HeaderFill = 'E8EEF6';

    public const string SectionFill = 'DCE9E2';

    public const string ZebraFill = 'F8FAFC';

    public const string Accent = '1F6B4F';

    public const string Danger = 'B42318';

    public const string DangerFill = 'FDECEC';

    public const string CurrencyFormat = '"NGN" #,##0.00';

    public const string DateFormat = 'd mmm yyyy';

    public const string DateTimeFormat = 'd mmm yyyy, hh:mm';

    public function workbook(string $title, string $subject): Spreadsheet
    {
        $spreadsheet = new Spreadsheet;
        $spreadsheet->getProperties()
            ->setCreator(config('app.name'))
            ->setLastModifiedBy(config('app.name'))
            ->setTitle($title)
            ->setSubject($subject)
            ->setDescription("Generated by {$this->productName()}.");
        $spreadsheet->getDefaultStyle()->getFont()
            ->setName('Aptos')
            ->setSize(10)
            ->getColor()
            ->setARGB(self::Ink);

        return $spreadsheet;
    }

    public function prepareSheet(
        Worksheet $sheet,
        string $title,
        string $orientation = PageSetup::ORIENTATION_PORTRAIT,
    ): void {
        $sheet->setTitle($title);
        $sheet->setShowGridlines(false);
        $sheet->getPageSetup()
            ->setOrientation($orientation)
            ->setPaperSize(PageSetup::PAPERSIZE_A4)
            ->setFitToWidth(1)
            ->setFitToHeight(0);
        $sheet->getPageMargins()
            ->setTop(0.5)
            ->setRight(0.35)
            ->setBottom(0.55)
            ->setLeft(0.35)
            ->setHeader(0.2)
            ->setFooter(0.25);
        $sheet->getHeaderFooter()->setOddFooter('&L'.$this->productName().'&RPage &P of &N');
    }

    public function documentTitle(Worksheet $sheet, string $range, int $size = 18): void
    {
        $sheet->getStyle($range)->applyFromArray([
            'font' => ['bold' => true, 'size' => $size, 'color' => ['argb' => self::Ink]],
            'alignment' => ['horizontal' => Alignment::HORIZONTAL_LEFT, 'vertical' => Alignment::VERTICAL_CENTER],
        ]);
    }

    public function documentSubtitle(Worksheet $sheet, string $range): void
    {
        $sheet->getStyle($range)->applyFromArray([
            'font' => ['bold' => true, 'size' => 11, 'color' => ['argb' => self::Accent]],
            'alignment' => ['horizontal' => Alignment::HORIZONTAL_LEFT, 'vertical' => Alignment::VERTICAL_CENTER],
        ]);
    }

    public function metadataLabel(Worksheet $sheet, string $range): void
    {
        $sheet->getStyle($range)->applyFromArray([
            'font' => ['bold' => true, 'size' => 9, 'color' => ['argb' => self::Muted]],
            'alignment' => ['vertical' => Alignment::VERTICAL_TOP],
        ]);
    }

    public function metadataValue(Worksheet $sheet, string $range): void
    {
        $sheet->getStyle($range)->applyFromArray([
            'font' => ['bold' => true, 'color' => ['argb' => self::Ink]],
            'alignment' => ['vertical' => Alignment::VERTICAL_TOP, 'wrapText' => true],
        ]);
    }

    public function sectionHeader(Worksheet $sheet, string $range): void
    {
        $sheet->getStyle($range)->applyFromArray([
            'font' => ['bold' => true, 'size' => 11, 'color' => ['argb' => self::Ink]],
            'fill' => ['fillType' => Fill::FILL_SOLID, 'startColor' => ['argb' => self::SectionFill]],
            'borders' => ['bottom' => ['borderStyle' => Border::BORDER_MEDIUM, 'color' => ['argb' => self::Accent]]],
            'alignment' => ['vertical' => Alignment::VERTICAL_CENTER],
        ]);
    }

    public function tableHeader(Worksheet $sheet, string $range): void
    {
        $sheet->getStyle($range)->applyFromArray([
            'font' => ['bold' => true, 'size' => 9, 'color' => ['argb' => self::Muted]],
            'fill' => ['fillType' => Fill::FILL_SOLID, 'startColor' => ['argb' => self::HeaderFill]],
            'borders' => ['allBorders' => ['borderStyle' => Border::BORDER_THIN, 'color' => ['argb' => self::Border]]],
            'alignment' => [
                'horizontal' => Alignment::HORIZONTAL_LEFT,
                'vertical' => Alignment::VERTICAL_CENTER,
                'wrapText' => true,
            ],
        ]);
    }

    public function summaryRow(Worksheet $sheet, string $range): void
    {
        $sheet->getStyle($range)->applyFromArray([
            'font' => ['bold' => true, 'color' => ['argb' => self::Ink]],
            'fill' => ['fillType' => Fill::FILL_SOLID, 'startColor' => ['argb' => self::HeaderFill]],
            'borders' => ['top' => ['borderStyle' => Border::BORDER_MEDIUM, 'color' => ['argb' => self::Border]]],
            'alignment' => ['vertical' => Alignment::VERTICAL_CENTER],
        ]);
    }

    public function tableBody(
        Worksheet $sheet,
        int $startRow,
        int $endRow,
        string $endColumn,
        bool $zebra = true,
    ): void {
        if ($endRow < $startRow) {
            return;
        }

        $sheet->getStyle("A{$startRow}:{$endColumn}{$endRow}")->applyFromArray([
            'borders' => ['allBorders' => ['borderStyle' => Border::BORDER_HAIR, 'color' => ['argb' => self::Border]]],
            'alignment' => ['vertical' => Alignment::VERTICAL_TOP],
        ]);

        if (! $zebra) {
            return;
        }

        for ($row = $startRow; $row <= $endRow; $row++) {
            if (($row - $startRow) % 2 === 1) {
                $sheet->getStyle("A{$row}:{$endColumn}{$row}")->getFill()
                    ->setFillType(Fill::FILL_SOLID)
                    ->getStartColor()
                    ->setARGB(self::ZebraFill);
            }
        }
    }

    /**
     * @param  array<string, float|int>  $widths
     */
    public function columnWidths(Worksheet $sheet, array $widths): void
    {
        foreach ($widths as $column => $width) {
            $sheet->getColumnDimension($column)->setWidth($width);
        }
    }

    public function text(Worksheet $sheet, string $coordinate, ?string $value): void
    {
        $sheet->setCellValueExplicit($coordinate, $value ?? '', DataType::TYPE_STRING);
    }

    public function date(Worksheet $sheet, string $coordinate, ?DateTimeInterface $value, bool $includeTime = false): void
    {
        if ($value === null) {
            $sheet->setCellValue($coordinate, null);

            return;
        }

        $sheet->setCellValue($coordinate, Date::PHPToExcel($value));
        $sheet->getStyle($coordinate)->getNumberFormat()
            ->setFormatCode($includeTime ? self::DateTimeFormat : self::DateFormat);
    }

    public function grade(Worksheet $sheet, string $coordinate, ?string $grade): void
    {
        $this->text($sheet, $coordinate, $grade);

        if ($grade === null || $grade === '') {
            return;
        }

        $color = match (strtoupper($grade)) {
            'A' => '16803C',
            'B' => '65A30D',
            'C' => 'A16207',
            'D' => 'D97706',
            'E' => 'EA580C',
            'F' => 'DC2626',
            default => self::Ink,
        };

        $sheet->getStyle($coordinate)->getFont()
            ->setBold(true)
            ->getColor()
            ->setARGB($color);
        $sheet->getStyle($coordinate)->getAlignment()->setHorizontal(Alignment::HORIZONTAL_CENTER);
    }

    public function shortLevel(string $levelName): string
    {
        if (preg_match('/^(?<level>\d+)00 Level$/', $levelName, $matches) === 1) {
            return $matches['level'].'00L';
        }

        return str_replace(' Level', 'L', $levelName);
    }

    public function qualifiedSemester(string $levelName, string $semesterName): string
    {
        return $this->shortLevel($levelName).' '.$semesterName.' Semester';
    }

    public function status(Worksheet $sheet, string $coordinate, string $status): void
    {
        $color = match (strtolower($status)) {
            'paid', 'approved', 'published' => '16803C',
            'pending', 'submitted' => 'A16207',
            'failed', 'returned' => self::Danger,
            default => self::Muted,
        };

        $this->text($sheet, $coordinate, $status);
        $sheet->getStyle($coordinate)->getFont()->setBold(true)->getColor()->setARGB($color);
    }

    private function productName(): string
    {
        return (string) config('app.name', 'GradeManager');
    }
}
